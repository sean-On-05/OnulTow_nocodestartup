// Helper to construct a 5-page briefing for a given category in Demo mode
export function getDemoBriefing(category: NewsCategory = 'it'): DailyBriefing {
  const categoryInfo = CATEGORIES[category] || CATEGORIES.it;
  const interestList = DEMO_INTEREST_NEWS[category] || DEMO_INTEREST_NEWS.it;

  const pages = [0, 1, 2, 3, 4].map((index) => ({
    pageNumber: index + 1,
    majorNews: DEMO_MAJOR_NEWS[index],
    interestNews: interestList[index],
  }));

  const todayStr = new Intl.DateTimeFormat('ko-KR', {
    timeZone: 'Asia/Seoul',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  })
    .format(new Date())
    .replace(/\. /g, '-')
    .replace('.', '');

  return {
    date: todayStr,
    category,
    categoryName: categoryInfo.name,
    pages,
    updatedAt: new Date().toLocaleTimeString('ko-KR', {
      timeZone: 'Asia/Seoul',
      hour: '2-digit',
      minute: '2-digit',
    }),
    isDemo: true,
    statusMessage: '예시 뉴스 / 데모 모드 (실제 RSS 연결 실패 또는 데모 모드 활성화)',
  };
}
